package com.ej1.app.shared.infrastructure.persistence;

import jakarta.persistence.Column;
import jakarta.persistence.MappedSuperclass;
import lombok.Getter;
import lombok.Setter;
import org.hibernate.annotations.CreationTimestamp;
import org.hibernate.annotations.UpdateTimestamp;

import java.time.LocalDateTime;

/**
 * Base for JPA entities carrying the standard {@code created_at}/{@code updated_at}
 * columns, populated by Hibernate ({@link CreationTimestamp}/{@link UpdateTimestamp})
 * rather than by application code.
 */
@MappedSuperclass
@Getter
@Setter
public abstract class AuditableEntity {

    @CreationTimestamp
    @Column(name = "created_at", nullable = false, updatable = false)
    private LocalDateTime createdAt;

    @UpdateTimestamp
    @Column(name = "updated_at", nullable = false)
    private LocalDateTime updatedAt;
}
